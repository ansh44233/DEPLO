import { createHmac, timingSafeEqual } from "node:crypto";
import { assessRecoveryResourceIdentities, type RecoveryResourceIdentity } from "./recovery-resource-identity";

export type SignedRecoveryInventoryPayload = Readonly<{
  version: 1;
  nonce: string;
  issuedAtMs: number;
  jobId: string;
  resources: readonly RecoveryResourceIdentity[];
}>;

export type SignedRecoveryInventoryEnvelope = Readonly<{
  payload: SignedRecoveryInventoryPayload;
  signature: string;
}>;

export type RecoveryInventoryVerification = Readonly<{
  authenticated: boolean;
  identitiesConsistent: boolean;
  cleanupAuthorized: false;
  resourceIds: readonly string[];
  blockers: readonly string[];
}>;

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const RESOURCE_ID = /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$/;
const MAX_INVENTORY_AGE_MS = 60_000;
const MAX_FUTURE_SKEW_MS = 5_000;

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function exactKeys(value: Record<string, unknown>, expected: readonly string[]): boolean {
  const actual = Object.keys(value).sort();
  return actual.length === expected.length && actual.every((key, index) => key === [...expected].sort()[index]);
}

function parseResources(value: unknown): RecoveryResourceIdentity[] | null {
  if (!Array.isArray(value) || value.length > 32) return null;
  const resources: RecoveryResourceIdentity[] = [];
  for (const item of value) {
    if (!isPlainRecord(item) || !exactKeys(item, ["kind", "resourceId", "jobId", "ownershipToken"])) return null;
    if (
      (item.kind !== "workspace" && item.kind !== "vm") ||
      typeof item.resourceId !== "string" || !RESOURCE_ID.test(item.resourceId) ||
      typeof item.jobId !== "string" || !UUID.test(item.jobId) ||
      typeof item.ownershipToken !== "string" || !UUID.test(item.ownershipToken)
    ) return null;
    resources.push({
      kind: item.kind,
      resourceId: item.resourceId,
      jobId: item.jobId,
      ownershipToken: item.ownershipToken,
    });
  }
  return resources;
}

function canonicalPayload(payload: SignedRecoveryInventoryPayload): string {
  return JSON.stringify({
    version: payload.version,
    nonce: payload.nonce,
    issuedAtMs: payload.issuedAtMs,
    jobId: payload.jobId,
    resources: payload.resources.map((resource) => ({
      kind: resource.kind,
      resourceId: resource.resourceId,
      jobId: resource.jobId,
      ownershipToken: resource.ownershipToken,
    })),
  });
}

function failure(...blockers: string[]): RecoveryInventoryVerification {
  return Object.freeze({
    authenticated: false,
    identitiesConsistent: false,
    cleanupAuthorized: false,
    resourceIds: Object.freeze([]),
    blockers: Object.freeze([...new Set(blockers)]),
  });
}

/**
 * Verifies a host-signed, request-bound inventory snapshot.
 *
 * The caller must supply a fresh one-time nonce generated by a trusted
 * supervisor and consume it atomically after successful verification.
 * This function authenticates the signer and payload only; it never
 * authorizes host actions or recovery-ledger acknowledgement.
 */
export function verifySignedRecoveryInventory(
  envelope: unknown,
  options: Readonly<{
    secret: unknown;
    expectedNonce: unknown;
    expectedJobId: unknown;
    expectedResources: unknown;
    nowMs?: unknown;
  }>,
): RecoveryInventoryVerification {
  try {
    if (!isPlainRecord(envelope) || !exactKeys(envelope, ["payload", "signature"])) {
      return failure("invalid_inventory_envelope");
    }
    if (!isPlainRecord(envelope.payload) || !exactKeys(envelope.payload, [
      "version", "nonce", "issuedAtMs", "jobId", "resources",
    ])) return failure("invalid_inventory_payload");

    const payload = envelope.payload;
    if (
      payload.version !== 1 ||
      typeof payload.nonce !== "string" || !UUID.test(payload.nonce) ||
      typeof payload.issuedAtMs !== "number" || !Number.isSafeInteger(payload.issuedAtMs) ||
      typeof payload.jobId !== "string" || !UUID.test(payload.jobId)
    ) return failure("invalid_inventory_payload");

    const resources = parseResources(payload.resources);
    if (!resources) return failure("invalid_inventory_resources");
    if (
      typeof options.secret !== "string" || Buffer.byteLength(options.secret, "utf8") < 32 ||
      typeof options.expectedNonce !== "string" || !UUID.test(options.expectedNonce) ||
      typeof options.expectedJobId !== "string" || !UUID.test(options.expectedJobId)
    ) return failure("invalid_inventory_verification_config");

    const nowMs = options.nowMs === undefined ? Date.now() : options.nowMs;
    if (typeof nowMs !== "number" || !Number.isSafeInteger(nowMs)) {
      return failure("invalid_inventory_verification_config");
    }
    if (payload.nonce !== options.expectedNonce) return failure("inventory_nonce_mismatch");
    if (payload.jobId !== options.expectedJobId || resources.some((item) => item.jobId !== payload.jobId)) {
      return failure("inventory_job_mismatch");
    }
    if (
      payload.issuedAtMs > nowMs + MAX_FUTURE_SKEW_MS ||
      nowMs - payload.issuedAtMs > MAX_INVENTORY_AGE_MS
    ) return failure("inventory_snapshot_stale");

    if (typeof envelope.signature !== "string" || !/^[0-9a-f]{64}$/i.test(envelope.signature)) {
      return failure("invalid_inventory_signature");
    }
    const expected = createHmac("sha256", options.secret)
      .update(canonicalPayload({
        version: 1,
        nonce: payload.nonce,
        issuedAtMs: payload.issuedAtMs,
        jobId: payload.jobId,
        resources,
      }))
      .digest();
    const supplied = Buffer.from(envelope.signature, "hex");
    if (supplied.length !== expected.length || !timingSafeEqual(supplied, expected)) {
      return failure("inventory_signature_mismatch");
    }

    const assessment = assessRecoveryResourceIdentities(
      options.expectedJobId,
      options.expectedResources,
      resources,
    );
    if (!assessment.identitiesConsistent) {
      return Object.freeze({
        authenticated: true,
        identitiesConsistent: false,
        cleanupAuthorized: false,
        resourceIds: Object.freeze([]),
        blockers: Object.freeze([...assessment.blockers]),
      });
    }

    return Object.freeze({
      authenticated: true,
      identitiesConsistent: true,
      cleanupAuthorized: false,
      resourceIds: Object.freeze([...assessment.matchedResourceIds]),
      blockers: Object.freeze([]),
    });
  } catch {
    return failure("invalid_inventory_envelope");
  }
}
